// Original synthetic SPC fixtures, no commercial game data.
function spc({ noise = false, echo = false } = {}) {
  const bytes = Buffer.alloc(0x10200);
  bytes.write('SNES-SPC700 Sound File Data v0.30', 0, 'ascii');
  bytes[0x21] = 0x1a; bytes[0x22] = 0x1a; bytes[0x23] = 0x1a; bytes[0x24] = 30;
  bytes.writeUInt16LE(0x200, 0x25); bytes[0x2b] = 0xff;
  bytes.write('Synthetic OPL4 test', 0x2e); bytes.write('spc2vgm web tests', 0x4e);
  bytes.write('003', 0xa9); bytes.write('00000', 0xac); bytes.write('spc2vgm', 0xb1);
  const ram = bytes.subarray(0x100, 0x10100), dsp = bytes.subarray(0x10100, 0x10180);
  dsp[0x5d] = 0x10; dsp[0x6c] = 0x20;
  ram.writeUInt16LE(0x1100, 0x1000); ram.writeUInt16LE(0x1100, 0x1002);
  // One looped BRR block containing a simple waveform.
  ram.set([0xb3, 0x12, 0x34, 0x56, 0x76, 0x54, 0x32, 0x10, 0xfe], 0x1100);
  const registers = [[0x6c, noise ? 0x3f : (echo ? 0 : 0x20)], [0x5d, 0x10], [0x0c, 0x7f], [0x1c, 0x7f],
    [0x00, 0x60], [0x01, 0x50], [0x02, 0], [0x03, 0x10], [0x04, 0], [0x05, 0], [0x07, 0x7f]];
  if (noise) registers.push([0x3d, 1]);
  if (echo) registers.push([0x2c, 0x30], [0x3c, 0x30], [0x0d, 0x30], [0x4d, 1], [0x6d, 0x30], [0x7d, 1], [0x0f, 0x7f]);
  registers.push([0x4c, 1]);
  let pc = 0x200;
  for (const [reg, value] of registers) {
    ram.set([0x8f, reg, 0xf2, 0x8f, value, 0xf3], pc); pc += 6;
  }
  ram.set([0x2f, 0xfe], pc); // BRA -2, DSP continues running.
  return bytes;
}
module.exports = { spc };
